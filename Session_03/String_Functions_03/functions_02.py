"""
Functions that will specifically work for string.
Capitalize/Title/Upper/Lower/Swapcase.
"""
s = 'hello world'
print(s.capitalize())
# Hello world

print(s.title())
# Hello World

print(s.upper())
# HELLO WORLD

print(s.lower())
# hello world

print(s.swapcase()) # -> This function will turn lower one to upper and upper character to lower.
# HELLO WORLD 