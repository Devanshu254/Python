# If a string contains characters then it's true and if the string is empty then it's false.
print('hello' and 'world') # True and True == True. In 'and' the output will be the second string.
# Output:world
print('hello' or 'world') # In case of 'or' the output will be the first string always.
# Output: hello
print('' and world)
# Output: empty
print('' or 'world')
# Output: world
print(not '')
# Output: True
print(not 'hello')
# Output: False